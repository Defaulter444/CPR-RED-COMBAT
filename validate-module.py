"""Browser checks against a public-API fixture, not a licensed Foundry runtime."""
import json, os, shutil
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT = Path(__file__).parent
BASE = os.environ.get('REDLINE_BASE_URL', 'http://127.0.0.1:8765').rstrip('/')
checks = []
def ok(name, value):
    assert value, name
    checks.append({'check': name, 'status': 'passed'})
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or shutil.which('chromium'), headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 1366, 'height': 768})
    errors = []; page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE + '/tests/module/host.html')
    page.wait_for_selector('#redline-combat-hud .redline-dock')
    ok('Startup reads live fixture documents without world writes', page.evaluate('fixture.records.documentWrites === 0'))
    ok('Hidden combatant omitted from DOM and public projection', page.locator('text=СЕКРЕТНЫЙ УЧАСТНИК').count() == 0 and page.evaluate("!JSON.stringify(fixture.api.getState()).includes('СЕКРЕТНЫЙ')"))
    ok('Enemy resources not projected and enemy selection disabled', page.locator('[data-id="c2"]').is_disabled() and page.evaluate("fixture.api.getState().combat.combatants.every(row => !('hp' in row))"))
    ok('Only visible target is included', page.evaluate("fixture.api.getState().targets.length === 1 && fixture.api.getState().targets[0].name === 'Охранник'"))
    ok('Player next turn disabled', page.locator('[data-action="next-turn"]').is_disabled())
    page.mouse.click(450, 360)
    ok('Center allows canvas click-through', page.evaluate('fixture.records.canvasClicks === 1'))
    page.locator('[data-id="c1"]').click()
    page.wait_for_function("fixture.api.getState().selected.name === 'Никс'")
    ok('Queue actor selection is independent from active turn', page.evaluate("fixture.combat.turn === 0 && fixture.api.getState().combat.combatants.find(row => row.current).id === 'c0'"))
    page.locator('[data-action="sheet"]').click()
    page.wait_for_function('fixture.records.sheetOpens === 1')
    page.evaluate('fixture.selectToken(0); fixture.updateHP(29)')
    page.wait_for_function("document.querySelector('.redline-health').textContent.includes('29')")
    ok('Actor update hook refreshes selected HP', page.evaluate('fixture.api.getState().selected.hp.value === 29'))
    for _ in range(3):
        page.evaluate('fixture.api.refresh()')
        page.wait_for_timeout(80)
    page.locator('[data-action="sheet"]').click()
    page.wait_for_function('fixture.records.sheetOpens === 2')
    page.wait_for_timeout(100)
    ok('Re-render replaces listeners without repeated sheet actions', page.evaluate('fixture.records.sheetOpens === 2'))
    ok('Selection and sheet opening do not write world documents', page.evaluate('fixture.records.documentWrites === 0'))
    page.evaluate('fixture.setGM(true)')
    page.wait_for_function("!document.querySelector('[data-action=\"next-turn\"]').disabled")
    page.locator('[data-action="next-turn"]').dblclick()
    page.wait_for_function('fixture.records.documentWrites === 1')
    page.wait_for_timeout(250)
    ok('Explicit GM double-click advances native combat once', page.evaluate('fixture.records.turnCalls === 1 && fixture.combat.turn === 1'))
    page.evaluate('fixture.setGM(false)')
    page.wait_for_function("document.querySelector('[data-action=\"next-turn\"]').disabled")
    page.locator('[data-action="next-turn"]').dispatch_event('click')
    page.wait_for_timeout(100)
    ok('Unauthorized synthetic next-turn click performs no write', page.evaluate('fixture.records.turnCalls === 1'))
    page.locator('[data-action="demo"]').click()
    page.wait_for_selector('#redline-combat-demo iframe')
    frame = page.frame_locator('#redline-combat-demo iframe')
    frame.locator('.dock').wait_for()
    ok('Packaged demo iframe loads with bundled assets', frame.locator('.portrait').count() > 0)
    frame.locator('[data-action="attack"]').click()
    frame.locator('[data-action="execute"]').click()
    frame.locator('[data-action="decline"]').click()
    frame.locator('#role').select_option('gm')
    frame.locator('[data-action="apply"]').click()
    ok('Demo attack and GM apply leave real fixture HP/ammo/combat untouched', page.evaluate('fixture.hero.system.derivedStats.hp.value === 29 && fixture.hero.items[0].system.magazine.value === 8 && fixture.records.documentWrites === 1'))
    page.locator('[aria-label="Закрыть демо"]').click()
    page.wait_for_selector('#redline-combat-demo', state='detached')
    page.locator('[data-action="close"]').click()
    page.wait_for_selector('#redline-combat-hud', state='detached')
    page.evaluate("Hooks.callAll('updateActor', fixture.hero)")
    page.wait_for_timeout(100)
    ok('Closed HUD stays closed after document hooks', page.locator('#redline-combat-hud').count() == 0)
    page.locator('#fixture-tool').click()
    page.wait_for_selector('#redline-combat-hud .redline-dock')
    ok('Scene-control tool restores HUD', page.locator('.redline-identity h2').inner_text() == 'Вега')
    page.evaluate('fixture.emptyCombat(); fixture.selectToken(null)')
    page.wait_for_selector('.redline-empty')
    ok('Empty combat and absent actor have useful empty states', page.locator('.redline-unit').count() == 0 and page.locator('[data-action="next-turn"]').is_disabled())
    for width, height in [(1920, 1080), (1366, 768), (1093, 614)]:
        page.set_viewport_size({'width': width, 'height': height})
        page.evaluate('game.combat = fixture.combat; fixture.selectToken(0)')
        page.wait_for_selector('.redline-identity')
        ok(f'No viewport overflow at {width}x{height}', page.evaluate('document.documentElement.scrollWidth === innerWidth'))
    page.set_viewport_size({'width': 1366, 'height': 768})
    page.screenshot(path=str(ROOT / 'renders' / 'foundry-module-fixture-1366.png'))
    ok('No browser exceptions', not errors)
    browser.close()
result = {'scope': 'Browser public-API fixture only; zero real Foundry integration tests', 'passed': len(checks), 'failed': 0, 'checks': checks}
(ROOT / 'module-validation.json').write_text(json.dumps(result, ensure_ascii=False, indent=2))
print('PASSED', len(checks), '(API fixture; not Foundry)')
